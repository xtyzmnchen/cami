class PoemChar {
  const PoemChar(this.han, this.py);
  final String han;
  final String py;
}

class PoemLine {
  const PoemLine(this.chars);
  final List<PoemChar> chars;

  String get text => chars.map((c) => c.han).join();
  String get pinyin => chars.map((c) => c.py).join(' ');
}

class Poem {
  const Poem({
    required this.title,
    required this.titlePy,
    required this.author,
    required this.dynasty,
    required this.lines,
  });

  final String title;
  final String titlePy;
  final String author;
  final String dynasty;
  final List<PoemLine> lines;

  String get fullText => lines.map((l) => l.text).join('\n');
  String get speakText => lines.map((l) => l.text).join('，');
}

PoemLine _l(List<(String, String)> pairs) =>
    PoemLine([for (final p in pairs) PoemChar(p.$1, p.$2)]);

